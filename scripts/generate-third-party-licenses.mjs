import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

import { pnpmExecutable } from './platform-command.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'THIRD_PARTY_LICENSES.txt');
const require = createRequire(import.meta.url);

function productionPackagePaths() {
  const report = JSON.parse(
    execFileSync(pnpmExecutable(), ['licenses', 'list', '--prod', '--json'], {
      cwd: root,
      encoding: 'utf8',
      maxBuffer: 16 * 1024 * 1024,
    }),
  );
  const paths = [];
  for (const groups of Object.values(report)) {
    for (const group of groups) paths.push(...group.paths);
  }
  paths.push(dirname(require.resolve('electron/package.json')));
  return [...new Set(paths)];
}

function licenseFiles(packagePath) {
  return readdirSync(packagePath)
    .filter((name) => /^(licen[cs]e|copying|notice)(\.|$)/iu.test(name))
    .sort((left, right) => left.localeCompare(right));
}

function packageEntry(packagePath) {
  const metadata = JSON.parse(readFileSync(join(packagePath, 'package.json'), 'utf8'));
  const files = licenseFiles(packagePath);
  if (files.length === 0) throw new Error(`${metadata.name}@${metadata.version} has no license file`);
  const text = files
    .map((name) => `--- ${name} ---\n${readFileSync(join(packagePath, name), 'utf8').trim()}`)
    .join('\n\n');
  return {
    id: `${metadata.name}@${metadata.version}`,
    license: metadata.license ?? 'See included license text',
    homepage: metadata.homepage ?? metadata.repository?.url ?? '',
    text,
  };
}

function render() {
  const uniquePackages = new Map();
  for (const packagePath of productionPackagePaths()) {
    const entry = packageEntry(packagePath);
    uniquePackages.set(entry.id, entry);
  }

  const groups = new Map();
  for (const entry of uniquePackages.values()) {
    const digest = createHash('sha256').update(entry.text).digest('hex');
    const group = groups.get(digest) ?? { text: entry.text, packages: [] };
    group.packages.push(entry);
    groups.set(digest, group);
  }

  const sections = [...groups.values()]
    .map((group) => ({
      ...group,
      packages: group.packages.sort((left, right) => left.id.localeCompare(right.id)),
    }))
    .sort((left, right) => left.packages[0].id.localeCompare(right.packages[0].id))
    .map((group, index) => {
      const packages = group.packages
        .map(
          (entry) =>
            `- ${entry.id} | ${entry.license}${entry.homepage ? ` | ${entry.homepage}` : ''}`,
        )
        .join('\n');
      return `================================================================================\nLicense group ${index + 1}\n================================================================================\nPackages:\n${packages}\n\n${group.text}`;
    });

  return `Orbit Workbench - Complete Third-Party License Texts\n\nThis file is generated by scripts/generate-third-party-licenses.mjs from the installed production dependency graph. Electron is included explicitly because it is shipped as the desktop runtime. Packages with identical license text are grouped together; every shipped package and version remains listed. Chromium notices distributed with Electron are provided separately as THIRD_PARTY_LICENSES.chromium.html.\n\n${sections.join('\n\n')}\n`;
}

const generated = render();
if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== generated) {
    throw new Error('THIRD_PARTY_LICENSES.txt is stale; run pnpm licenses:generate');
  }
} else {
  writeFileSync(outputPath, generated, 'utf8');
}
